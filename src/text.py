"""Текст объявления для поиска: заголовок + очищенные параметры + начало описания.

item_infm_params_text — это склеенные без разделителей пары «ключ значение»:
«Вид услуги Красота, здоровье Место оказания услуг Москва, ... Тип стоимости за услугу Начальная цена ...».
Названия ключей и служебные значения (график, тип цены) повторяются почти в каждом объявлении,
поэтому совпадают с любым запросом со словом «услуги». Их убираем, значения услуг оставляем:
«Красота, здоровье», «Перманентный макияж», «Подготовка к международному экзамену».
"""
from __future__ import annotations

import re

import pandas as pd

# Служебные ключи и значения. Длинные фразы идут раньше коротких, чтобы вырезаться целиком.
BOILERPLATE = [
    "Время для связи, дни недели", "Время для связи от", "Время для связи до", "Время для связи",
    "Место оказания услуг", "Где вы оказываете услуги", "Кто оказывает услуги", "Как вы работаете",
    "Тип стоимости за услугу", "Тип стоимости за час", "Тип стоимости", "Начальная цена", "Стоимость",
    "Работаете с юрлицами и ИП", "Работа по договору", "Берёте ли срочные заказы", "Опыт работы",
    "Рабочие дни", "Ваши клиенты", "Продолжительность", "Предоплата", "Гарантия",
    "Название услуги", "Специальность или сфера", "Чем вы занимаетесь", "Предмет или специальность",
    "Тип услуги автосервиса", "Вид услуги", "Тип услуги", "Направление", "Услуги", "Услуга",
    "Понедельник", "Вторник", "Среда", "Четверг", "Пятница", "Суббота", "Воскресенье",
    "пн.", "вт.", "ср.", "чт.", "пт.", "сб.", "вс.",
    "Удалённо", "У себя", "У заказчика дома", "В салоне", "Женщины", "Мужчины", "Женщина", "Мужчина",
    "Частный исполнитель", "Компания",
    "График работы, дни недели", "График работы от", "График работы до", "График работы", "дни недели",
    "Минимальное время заказа", "Куда выезжаете", "По всему городу", "Готов закупить материалы",
    "Есть портфолио", "Учебное учреждение", "Год окончания", "Число мест", "Бригада", "человека", "человек",
    "Дополнительно", "Производители", "Марка", "Модель", "Своя", "лет и больше", "ч", "мин",
]
_BOILER_RE = re.compile(r"(?<!\w)(?:" + "|".join(re.escape(p) for p in sorted(BOILERPLATE, key=len, reverse=True))
                        + r")(?!\w)")
_NUM_RE = re.compile(r"\b\d[\d\s.,–-]*\b")      # цены, время в секундах, диапазоны «4–6 лет»
_WS_RE = re.compile(r"\s+")


def clean_params(s: pd.Series) -> pd.Series:
    """Убирает из параметров служебные ключи, дни недели и числа; значения услуг остаются."""
    s = s.fillna("").astype(str)
    s = s.str.replace(_BOILER_RE, " ", regex=True)
    s = s.str.replace(_NUM_RE, " ", regex=True)
    return s.str.replace(_WS_RE, " ", regex=True).str.strip()


def item_text(items: pd.DataFrame, desc_chars: int = 500) -> pd.Series:
    """Документ для поиска: заголовок. очищенные параметры. первые desc_chars символов описания.

    Описание обрезаем: медиана около 1 000 символов, а начало обычно самое содержательное
    и укладывается в окно моделей эмбеддингов.
    """
    title = items["item_title_raw"].fillna("").astype(str)
    params = clean_params(items["item_infm_params_text"])
    desc = (items["item_description_raw"].fillna("").astype(str)
            .str.replace(_WS_RE, " ", regex=True).str.slice(0, desc_chars))
    return title + ". " + params + ". " + desc
